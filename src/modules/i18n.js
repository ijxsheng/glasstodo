const regexMeta = '^$.*+?()[]{}|' + String.fromCharCode(92);
const escapeRegex = text => Array.from(text, char => regexMeta.includes(char) ? String.fromCharCode(92) + char : char).join('');
const pattern = new RegExp(Object.keys(translations).sort((a,b)=>b.length-a.length).map(escapeRegex).join('|'),'g');
export function translate(text, selectedLanguage = language) {
  if (selectedLanguage === 'zh') return text;
  return String(text).replace(pattern, key => translations[key]).replace(/。/g,'.').replace(/，/g,', ').replace(/；/g,'; ').replace(/：/g,': ').replace(/（/g,'(').replace(/）/g,')').replace(/、/g,', ').replace(/？/g,'?');
}
export const t = text => translate(text);
export function taskCount(count, selectedLanguage = language) {
  return selectedLanguage === 'zh' ? `${count} 项` : `${count} ${count === 1 ? 'task' : 'tasks'}`;
}
export function ui(strings, ...values) {
  return strings.reduce((output, chunk, index) => output + t(chunk) + (index < values.length ? String(values[index]) : ''), '');
}
