export function readLanguage(storage) {
  try {
    const source = storage === undefined && typeof window !== 'undefined' ? globalThis.localStorage : storage;
    return source?.getItem('glasstodo.ui.language') === 'zh' ? 'zh' : 'en';
  } catch { return 'en'; }
}
export const language = readLanguage();
export const locale = language === 'zh' ? 'zh-CN' : 'en-US';
export function saveLanguage(value, storage = globalThis.localStorage) {
  if (!['en','zh'].includes(value)) throw new Error('Unsupported language');
  storage?.setItem('glasstodo.ui.language', value);
}

